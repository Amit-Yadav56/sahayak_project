"""
train_ner.py
=============
Trains a real statistical spaCy `ner` pipeline component on the v3
extractor's silver-labeled spans (data/train.spacy), and evaluates on a
genuinely held-out dev set (data/dev.spacy) — not the training data
itself. Reports precision/recall/F1 per entity label, which is what
actually tells you whether this model generalizes past the rules it
was bootstrapped from.

Run:  python3 train_ner.py
Output: trained_model/  (a loadable spaCy pipeline directory)
"""

import random
from pathlib import Path

import spacy
from spacy.tokens import DocBin
from spacy.training import Example
from spacy.scorer import Scorer

TRAIN_FILE = Path("data/train.spacy")
DEV_FILE = Path("data/dev.spacy")
MODEL_OUT = Path("trained_model")
N_ITER = 6


def load_examples(path: Path, nlp) -> list[Example]:
    doc_bin = DocBin().from_disk(path)
    docs = list(doc_bin.get_docs(nlp.vocab))
    return [Example(nlp.make_doc(doc.text), doc) for doc in docs]


def main():
    if not TRAIN_FILE.exists() or not DEV_FILE.exists():
        raise SystemExit(f"{TRAIN_FILE} / {DEV_FILE} not found — run generate_training_data.py first.")

    nlp = spacy.blank("en")
    ner = nlp.add_pipe("ner")

    train_examples = load_examples(TRAIN_FILE, nlp)
    dev_examples = load_examples(DEV_FILE, nlp)

    if not train_examples:
        raise SystemExit("No training examples found — did generate_training_data.py run cleanly?")

    labels_seen = set()
    for ex in train_examples:
        for ent in ex.reference.ents:
            ner.add_label(ent.label_)
            labels_seen.add(ent.label_)

    print(f"Training on {len(train_examples)} example(s), evaluating on {len(dev_examples)} held-out "
          f"example(s), {len(labels_seen)} label(s): {sorted(labels_seen)}\n")

    optimizer = nlp.initialize(lambda: train_examples)

    for i in range(N_ITER):
        random.shuffle(train_examples)
        losses = {}
        # batch training so it doesn't choke on 3000+ examples in one update
        batch_size = 64
        for j in range(0, len(train_examples), batch_size):
            batch = train_examples[j:j + batch_size]
            nlp.update(batch, sgd=optimizer, losses=losses, drop=0.2)
        if (i + 1) % 5 == 0 or i == 0:
            print(f"  iter {i + 1:>2}/{N_ITER}  loss={losses.get('ner', 0):.2f}")

    MODEL_OUT.mkdir(parents=True, exist_ok=True)
    nlp.to_disk(MODEL_OUT)
    print(f"\nSaved trained pipeline -> {MODEL_OUT}/")

    # --- Real evaluation on held-out dev set ---
    print("\n" + "=" * 60)
    print("DEV SET EVALUATION (held out — never seen during training)")
    print("=" * 60)

    scorer = Scorer()
    scored_examples = []
    for ex in dev_examples:
        pred = nlp(ex.reference.text)
        scored_examples.append(Example(pred, ex.reference))

    scores = scorer.score(scored_examples)

    print(f"\nOverall: P={scores['ents_p']:.3f}  R={scores['ents_r']:.3f}  F1={scores['ents_f']:.3f}\n")
    print(f"{'Label':<14}{'P':>8}{'R':>8}{'F1':>8}")
    per_type = scores.get("ents_per_type", {})
    for label, metrics in sorted(per_type.items()):
        print(f"{label:<14}{metrics['p']:>8.3f}{metrics['r']:>8.3f}{metrics['f']:>8.3f}")

    print("\nNote: this model was trained on labels generated by the rule-based")
    print("extractor itself (silver/weak supervision) — high dev F1 here means")
    print("the model learned to REPRODUCE the rules' decision boundary, not that")
    print("it's correct against ground truth. It's a meaningful signal of whether")
    print("the model generalizes past exact rule wording, not a substitute for")
    print("eventually checking against a small human-annotated sample.")


if __name__ == "__main__":
    main()
